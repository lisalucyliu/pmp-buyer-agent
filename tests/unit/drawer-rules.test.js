// Free tests. No Claude calls. Run: npm run test:unit
import assert from 'node:assert/strict';
import { readFileSync, readdirSync } from 'node:fs';
import { test } from 'node:test';
import { PRODUCTS, experienceFor, findBuyer } from '../../shared/catalog.js';
import { ERROR_TYPE, errorTypeForStatus } from '../../shared/errorTypes.js';
import { PAGE_CASE, productPageCase } from '../../shared/productPageCase.js';
import sampleRequests from '../../data/sampleRequests.json' with { type: 'json' };

const byName = (name) => PRODUCTS.find((p) => p.name === name);
const riley = findBuyer('riley');
const sam = findBuyer('sam');
const pageCase = (name, buyer, requests = sampleRequests) =>
  productPageCase({ product: byName(name), buyer, experience: experienceFor(buyer), requests });

test('U11: 429 and 529 give E1a (busy); 401, 403, 500 and an unknown status give E1b (not available)', () => {
  assert.equal(errorTypeForStatus(429), ERROR_TYPE.E1A);
  assert.equal(errorTypeForStatus(529), ERROR_TYPE.E1A);
  for (const status of [401, 403, 500, 502, 418, undefined]) assert.equal(errorTypeForStatus(status), ERROR_TYPE.E1B, String(status));
});

test('E1 (unit): frame 3 has 5 cases, chosen by code', () => {
  assert.equal(pageCase('Meshwire', riley), PAGE_CASE.REQUESTABLE);
  assert.equal(pageCase('QuarryDB Cloud (pay-as-you-go)', riley), PAGE_CASE.PENDING);
  assert.equal(pageCase('Bastion NGFW VM', riley), PAGE_CASE.REQUESTABLE); // Declined is not Pending (Q9)
  assert.equal(pageCase('Tunnelport Access Server (BYOL)', riley), PAGE_CASE.APPROVED);
  assert.equal(pageCase('Meshwire', sam), PAGE_CASE.REQUESTS_OFF);
  assert.equal(pageCase('Lumora Image Large', riley), PAGE_CASE.BLOCKED);
  assert.equal(pageCase('Breachkit Linux', sam), PAGE_CASE.REQUESTS_OFF); // decision 1
  assert.equal(pageCase('Lakeforge Data Platform', sam), PAGE_CASE.APPROVED);
});

function sourceFiles(dir) {
  return readdirSync(new URL(dir, import.meta.url), { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory() ? sourceFiles(`${dir}${entry.name}/`) : [[`${dir}${entry.name}`, readFileSync(new URL(`${dir}${entry.name}`, import.meta.url), 'utf8')]]);
}

test('U12: no output label, regenerate or stop button in the drawer source (parking lot, decisions 95, 98)', () => {
  for (const [file, text] of sourceFiles('../../src/drawer/')) {
    assert.ok(!/Generated by AI/i.test(text), `${file} has an output label`);
    assert.ok(!/regenerat/i.test(text), `${file} has regenerate`);
    assert.ok(!/stop generat|Stop response|iconName="stop/i.test(text), `${file} has a stop button`);
  }
});

test('decision 110: the drawer never renders Claude text as HTML or markdown', () => {
  for (const [file, text] of sourceFiles('../../src/')) {
    assert.ok(!text.includes('dangerouslySetInnerHTML'), file);
    assert.ok(!/markdown/i.test(text.replace(/\/\/.*$/gm, '')), `${file} uses a markdown renderer`);
  }
});

test('no em dashes in app source, shared copy or data', () => {
  for (const dir of ['../../src/', '../../shared/', '../../data/']) {
    for (const [file, text] of sourceFiles(dir)) assert.ok(!text.includes('—'), file);
  }
});
